"""Sandbox: how wide are the flat tori of N points, counted? Usage: python sandbox/flat_torus_widths.py

A flat torus here is the square grid wrapped by a lattice of N-step translations with no wrap shorter than six
steps (every edge then carries exactly two squares, so its energy is zero at every curling cost). Each such
wrapping is one arrangement; they all cost the same, so if the toy could move freely among them it would visit them
equally. This counts them by width, the length of the shortest way round.

A wrapping is a sublattice of the grid with N points per cell: generated by (a, 0) and (b, d) with a*d = N and
0 <= b < a. Two-sidedness needs every wrap to have even length: a even and b + d even.
"""
import sys


def width(a, b, d):
    """The shortest nonzero wrap m*(a, 0) + n*(b, d), measured in grid steps."""
    best = a
    n = 1
    while n * d < best:
        r = (n * b) % a
        best = min(best, min(r, a - r) + n * d)
        n += 1
    return best


def count(n_points):
    """{width: number of wrappings} over two-sided wrappings of N points with no wrap shorter than six."""
    out = {}
    for a in range(2, n_points + 1, 2):
        if n_points % a:
            continue
        d = n_points // a
        for b in range(a):
            if (b + d) % 2:
                continue
            w = width(a, b, d)
            if w >= 6:
                out[w] = out.get(w, 0) + 1
    return out


def main(sizes=(64, 96, 144, 192, 288, 1024, 4096)):
    print("N: flat wrappings | share six around | median width | widest | sqrt(2N)")
    for n in sizes:
        c = count(n)
        total = sum(c.values())
        running, median = 0, None
        for w in sorted(c):
            running += c[w]
            if median is None and 2 * running >= total:
                median = w
        print("%5d: %6d | %5.1f %% | %3d | %3d | %.1f   %s"
              % (n, total, 100.0 * c.get(6, 0) / total, median, max(c), (2 * n) ** 0.5,
                 " ".join("%d:%d" % kv for kv in sorted(c.items())[:12])))


if __name__ == "__main__":
    main(tuple(int(x) for x in sys.argv[1:]) or (64, 96, 144, 192, 288, 1024, 4096))
