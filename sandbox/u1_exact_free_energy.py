def say(s=""):
    print(s, flush=True)
    lines.append(s)


KMAX = 60  # truncation of each integer coefficient; checked against KMAX // 2 below


def ratios(beta, kmax=KMAX):
    """r_n = I_n(beta) / I_0(beta) for n = 0..2*kmax (index by |n|)."""
    n = np.arange(0, 2 * kmax + 1)
    return ive(n, beta) / ive(0, beta)


def null_dim(f):
    return f.n_squares - np.linalg.matrix_rank(f.B.toarray())


def local_null_vector(B, support):
    """The +-1 integer null vector of B^T supported on `support` (squares), or raise."""
    sub = B[support, :]                      # rows = squares
    u, s, vt = np.linalg.svd(sub.T)          # columns = squares
    nul = int(np.sum(s < 1e-9)) + (len(support) - len(s))
    if nul != 1:
        raise ValueError(f"expected one null direction on the box, found {nul}")
    v = vt[-1] / np.abs(vt[-1]).max()
    if not np.allclose(np.abs(v), 1.0, atol=1e-9):
        raise ValueError("box null vector is not a sign vector")
    out = np.zeros(B.shape[0], dtype=np.int64)
    out[support] = np.sign(v).astype(np.int64)
    return out


class Sheet:
    """Any graph whose integer null lattice is one sign vector (flat torus)."""

    def __init__(self, dims):
        adj, part = torus(dims)
        self.f = Field(adj, part)
        self.P = self.f.n_squares
        assert null_dim(self.f) == 1
        self.e = self.f.square_signs()
        assert np.all((self.f.B.T @ self.e) == 0)

    def c(self, beta, kmax=KMAX):
        r = ratios(beta, kmax)[: kmax + 1]
        terms = np.concatenate([[1.0], 2.0 * r[1:] ** self.P])
        return float(np.log(np.sum(terms)))


class Tube:
    """The 4 x L tube: integer null lattice generated by the L boxes between neighbouring rings."""

    def __init__(self, L):
        adj, part = torus((4, L))
        self.L = L
        self.f = Field(adj, part)
        self.P = self.f.n_squares
        B = self.f.B.toarray()
        y = np.arange(4 * L) % L                     # coords (x, y), y fastest; axis 0 is the side of 4
        x = np.arange(4 * L) // L
        assert np.all(x * L + y == np.arange(4 * L))
        sq_y = [set(int(y[v]) for v in sq) for sq in self.f.squares]
        rings = {}
        between = {k: [] for k in range(L)}
        for p, ys in enumerate(sq_y):
            if len(ys) == 1:
                rings[next(iter(ys))] = p
            else:
                a, b = sorted(ys)
                lo = b if (a == 0 and b == L - 1) else a  # squares between rings lo and lo + 1
                between[lo].append(p)
        assert len(rings) == L and all(len(v) == 4 for v in between.values())
        assert self.P == 5 * L and null_dim(self.f) == L
        self.rings, self.between = rings, between
        self.boxes = np.array([local_null_vector(B, [rings[k], rings[(k + 1) % L]] + between[k]) for k in range(L)])
        assert np.all(self.boxes @ B == 0)
        assert np.linalg.matrix_rank(self.boxes.astype(float)) == L
        # ring k is shared by box k-1 (coefficient a) and box k (coefficient b): entry = sa*a + sb*b
        self.ring_signs = [(int(self.boxes[(k - 1) % L, rings[k]]), int(self.boxes[k, rings[k]])) for k in range(L)]
        # every square-between entry is +-1 times its own box coefficient
        for k in range(L):
            for p in between[k]:
                assert abs(self.boxes[k, p]) == 1 and np.sum(np.abs(self.boxes[:, p])) == 1

    def c(self, beta, kmax=KMAX):
        r = ratios(beta, kmax)
        ks = np.arange(-kmax, kmax + 1)
        diag = r[np.abs(ks)] ** 4                       # the box's 4 squares between rings
        logz = 0.0
        M = np.eye(len(ks))
        for k in range(self.L):
            sa, sb = self.ring_signs[k]
            W = r[np.abs(sa * ks[:, None] + sb * ks[None, :])]   # ring k: a = box k-1, b = box k
            M = M @ (W * diag[None, :])
            s = np.abs(M).max()
            M /= s
            logz += np.log(s)
        return float(logz + np.log(np.trace(M)))

    def c_bruteforce(self, beta, kmax):
        r = ratios(beta, kmax)
        tot = 0.0
        for cs in itertools.product(range(-kmax, kmax + 1), repeat=self.L):
            n = np.asarray(cs) @ self.boxes
            tot += np.prod(r[np.abs(n)])
        return float(np.log(tot))


def mean_sum_cos_exact(obj, beta, h=1e-4):
    """<sum_p cos phi_p> = d ln Z / d beta = P I1/I0 + dc/dbeta (central difference)."""
    lead = obj.P * ive(1, beta) / ive(0, beta)
    return lead + (obj.c(beta + h) - obj.c(beta - h)) / (2 * h)


