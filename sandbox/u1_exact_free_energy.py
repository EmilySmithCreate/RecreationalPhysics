def lam_eff_minus_1(n, beta, exact=True):
    sh, tu = pairs[n]
    lnI0 = np.log(ive(0, beta)) + beta
    d = (tu.P - sh.P) * lnI0 + ((tu.c(beta) - sh.c(beta)) if exact else 0.0)
    return (LAM - 1) - G * d / (4 * n)


zeros = {}
for n in pairs:
    bl = brentq(lambda b: lam_eff_minus_1(n, b, False), 0.5, 10.0, xtol=1e-10)
    be = brentq(lambda b: lam_eff_minus_1(n, b, True), 0.5, 10.0, xtol=1e-10)
    zeros[n] = (bl, be)
    say(f"N = {n}: lambda_eff - 1 reaches zero at beta = {bl:.4f} (leading order), {be:.4f} (exact); "
        f"if beta = kappa / g with g = {G}: kappa = {G * bl:.3f} (leading), {G * be:.3f} (exact)")
