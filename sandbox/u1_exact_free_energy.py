table = []
for n, (sh, tu) in pairs.items():
    dP = tu.P - sh.P
    for beta in betas:
        lnI0 = np.log(ive(0, beta)) + beta
        cs, ct = sh.c(beta), tu.c(beta)
        lead = dP * lnI0
        exact = lead + ct - cs
        le_lead = (LAM - 1) - G * lead / (4 * n)
        le_ex = (LAM - 1) - G * exact / (4 * n)
        table.append((n, beta, cs, ct, lead, exact, le_lead, le_ex))
        say(f"{n:>4} {beta:>5.1f} {cs:>12.6f} {ct:>12.6f} {lead:>11.4f} {exact:>11.4f} "
            f"{100 * (exact - lead) / lead:>7.2f} {le_lead:>15.5f} {le_ex:>16.5f}")
