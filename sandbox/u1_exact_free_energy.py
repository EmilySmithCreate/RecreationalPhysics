"""Exact ln Z_U1 of the lattice photon at fixed wiring, flat sheet against curled tube (24 October 2026).

Step 1 of docs/design/u1_rewiring_graph_brief_2026-10-24.md. Sandbox, exploratory; decides nothing.

Z_U1(G) = int prod_l dtheta_l / (2 pi) exp(beta sum_p cos phi_p), phases on the links, squares = every 4-cycle
(graphity.u1.Field). Character expansion (ours, exact; the same formula as Gate U1): exp(beta cos phi) =
sum_n I_n(beta) e^{i n phi}; integrating each link's phase forces sum_p n_p B_pl = 0, so

    Z_U1 = sum over integer n in ker_Z(B^T) of prod_p I_{n_p}(beta).

Both graphs at each N have the same number of links (2N), so the (2 pi)^links normalisation cancels in
tube-minus-sheet differences. We report c(G) = ln Z_U1 - P ln I0(beta) (P = number of squares), i.e. the
log of the sum with every I_n replaced by r_n = I_n / I0; the leading order sets c = 0.

The integer null lattice (checked below, not assumed):
* sheet L x L (and any flat torus, sides >= 6): one generator, the sign vector e of the whole surface; c = ln sum_k r_k^P.
* tube 4 x L: L generators, the closed box b_y = ring y, ring y+1 and the 4 squares between them, entries +-1. Each
  square between rings sits in exactly one box with coefficient +-1, so integer n forces integer coefficients: the
  boxes are an integer basis (not just a real one). A ring is shared by two neighbouring boxes; its entry is
  +-c_{y-1} +- c_y. So Z is the trace of a product of transfer matrices over the box coefficients, built below from
  the actual vectors (signs read off, not assumed) and checked against a brute-force lattice sum on a short tube.

Monte Carlo cross-check: graphity.u1.Field.metropolis at fixed wiring, d lnZ/d beta = <sum_p cos phi_p>, integrated
over beta from 0 (Simpson), and <sum cos> compared point by point with the exact derivative. The instanton move
exists only where B^T has one null direction (the sheet); on the tube the box sectors are crossed by single-link
moves (a box is 6 squares), which suffices at beta <= 2 (checked by agreement with the exact derivative).
"""
