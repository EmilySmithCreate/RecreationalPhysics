# ---------- Monte Carlo cross-check ----------
say("Monte Carlo cross-check at fixed wiring, N = 64 (graphity.u1.Field.metropolis; instanton move on the sheet only)")
grid = np.linspace(0.0, 2.0, 21)
N_EQ, N_MEAS, BIN = 2000, 20000, 500


def mc_curve(obj, use_inst, seed0):
    f = obj.f
    inst = f.instanton() if use_inst else None
    means, errs = [], []
    for i, beta in enumerate(grid):
        theta = np.zeros(f.n_links)
        step = min(np.pi, 2.5 / np.sqrt(max(beta, 0.3)))
        _, out, acc = f.metropolis(theta, beta, step, N_EQ, N_MEAS, seed0 + i, instanton=inst)
        s = out * f.n_squares
        b = s[: (len(s) // BIN) * BIN].reshape(-1, BIN).mean(axis=1)
        means.append(s.mean())
        errs.append(b.std(ddof=1) / np.sqrt(len(b)))
    return np.array(means), np.array(errs)


def simpson_weights(x):
    h = x[1] - x[0]
    w = np.ones(len(x))
    w[1:-1:2], w[2:-1:2] = 4, 2
    return w * h / 3


sh, tu = pairs[64]
ms, es = mc_curve(sh, True, 1000)
mt, et = mc_curve(tu, False, 2000)
say(f"{'beta':>5} {'<sum cos> sheet MC':>20} {'exact':>10} {'<sum cos> tube MC':>20} {'exact':>10}")
