"""Exact: the flat tori of N points, counted by width. Usage:

    python scripts/exact_flat_torus_widths.py [N ...]

A flat torus here is the square grid wrapped up by a lattice of translations with N points per cell and no wrap
shorter than six steps. Every edge then carries exactly two squares, so H = 0 at every lambda (checked on built
graphs in tests/test_flat_torus_widths.py). The width is the length of the shortest wrap, the shortest closed path
that cannot be shrunk to a point. The tube's end states in the lambda maps all but always have width 6
(ASSUMPTIONS O116); this counts how many flat tori of each width there are.

A wrapping is a sublattice of the grid of index N. In Hermite normal form it is generated by (a, 0) and (b, d) with
a d = N and 0 <= b < a, each sublattice exactly once. The graph is two-sided (bipartite) when every wrap has even
length: a even and b + d even.

Two caveats, said here once. Sublattices that are turns or mirror images of one another give the same graph, so the
count is of wrappings, not of graphs up to renaming; with named points each wrapping carries the same number of
labelled graphs, because a torus's renamings are its translations times the turns and mirrors that keep its
lattice (ours, unverified). And the zero-energy graphs are not only tori: a few saved end states read differently
from different points (O116) and are not counted here.
"""
import sys

import numpy as np


def width(a, b, d):
    """The shortest nonzero wrap m (a, 0) + n (b, d), in grid steps."""
    best = a
    n = 1
    while n * d < best:
        r = (n * b) % a
        best = min(best, min(r, a - r) + n * d)
        n += 1
    return best


def wrappings(n_points):
    """Every two-sided wrapping (a, b, d) of N points with no wrap shorter than six, with its width."""
    out = []
    for a in range(2, n_points + 1, 2):
        if n_points % a:
            continue
        d = n_points // a
        for b in range(a):
            if (b + d) % 2 == 0 and width(a, b, d) >= 6:
                out.append((a, b, d, width(a, b, d)))
    return out


def count(n_points):
    """{width: number of wrappings}."""
    out = {}
    for _a, _b, _d, w in wrappings(n_points):
        out[w] = out.get(w, 0) + 1
    return dict(sorted(out.items()))


def graph(a, b, d):
    """The wrapping as a neighbour array: points (x, y), 0 <= x < a, 0 <= y < d; a step past y = d - 1 arrives at
    (x - b, 0)."""
    def index(x, y):
        return (x % a) * d + y
    adj = np.empty((a * d, 4), dtype=np.int64)
    for x in range(a):
        for y in range(d):
            up = index(x - b, 0) if y == d - 1 else index(x, y + 1)
            down = index(x + b, d - 1) if y == 0 else index(x, y - 1)
            adj[index(x, y)] = (index(x + 1, y), index(x - 1, y), up, down)
    return adj


def median_width(counts):
    total, running = sum(counts.values()), 0
    for w in sorted(counts):
        running += counts[w]
        if 2 * running >= total:
            return w


def main(sizes=(64, 96, 144, 192, 288, 384, 1024, 4096)):
    print("N: flat wrappings | six around | median width | widest | sqrt(2N)")
    for n in sizes:
        c = count(n)
        total = sum(c.values())
        print("%5d: %5d | %3d = %4.1f %% | %3d | %3d | %.1f"
              % (n, total, c.get(6, 0), 100.0 * c.get(6, 0) / total, median_width(c), max(c), (2 * n) ** 0.5))


if __name__ == "__main__":
    main(tuple(int(x) for x in sys.argv[1:]) or (64, 96, 144, 192, 288, 384, 1024, 4096))
